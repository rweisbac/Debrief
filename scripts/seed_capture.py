"""Run the capture step on all 12 deals, score it against data/gold_capture, and fill the dashboard with
simulated AE confirms.

Replay mode (default) uses recorded fixtures only and reports a deal as not run when a recording is missing; it
never calls the API. Record mode (--mode record, needs a key) records the extraction and capture calls.

Writes evals/capture_results.md. Simulated confirms are stored with simulated=1 and shown as simulated.

Run: python scripts/seed_capture.py [--mode replay|record]
"""
from __future__ import annotations

import argparse
import asyncio
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from evals import capture_scoring as cs  # noqa: E402
from src import capture  # noqa: E402
from src.chain import Chain, DebriefResult, load_context  # noqa: E402
from src.llm import LLMClient, ReplayMiss  # noqa: E402

OUT = ROOT / "evals" / "capture_results.md"


async def run_one(deal_id: str, llm: LLMClient) -> dict:
    ctx = load_context(deal_id)
    result = DebriefResult(debrief_id=f"{deal_id}-seed", deal_id=deal_id, as_of=ctx.as_of.isoformat(),
                           mode=llm.mode, model=llm.model)
    ex = await Chain(llm).extract(ctx, result)
    if ex.parsed is None:
        return {"deal": deal_id, "status": "error", "reason": "extraction failed"}
    res = await capture.run_capture(llm, ctx.transcript, ctx.context_block(), ex.parsed, result.debrief_id)
    if res.parsed is None:
        return {"deal": deal_id, "status": "error", "reason": "capture failed: " + (res.parse_error or "refused")}
    scored = capture.score(res.parsed, ctx.transcript, ctx.crm, ctx.as_of)
    cap = capture.save_capture(deal_id, res.parsed, scored, llm.mode, result.debrief_id)
    ae = ctx.crm["owner_ae"]
    routing = capture.route(scored, ae_confirms_so_far=capture.ae_confirms(ae, simulated=True),
                            spot_key=cap["capture_id"])
    g = cs.gold(deal_id)
    edits, seconds, wrong = cs.simulate_ae(g, scored, routing)
    capture.submit(cap, ae, edits, seconds, simulated=True)
    return {"deal": deal_id, "status": "ran", "bucket": g["bucket"], "wrong": wrong,
            "asked": [f for f, r in routing.items() if r["mode"] == "ask"],
            "confidence": {f: scored[f]["confidence"] for f in capture.FIELDS},
            "cost_usd": res.cost_usd + ex.cost_usd}


def report(rows: list[dict], mode: str) -> str:
    ran = [r for r in rows if r["status"] == "ran"]
    L = ["# Capture results", "",
         "Synthetic data, fictional company. Generated by `scripts/seed_capture.py`. Ground truth in "
         "`data/gold_capture` was written by the builder and needs an independent review.", "",
         f"- Mode: {mode}. Generated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC.",
         f"- Deals run: {len(ran)} of {len(rows)}.", ""]
    if not ran:
        L += ["## Status: nothing ran", "", "No capture output has been recorded yet, so no scores exist. "
              "Run `python scripts/seed_capture.py --mode record` with a key to record it.", ""]
    else:
        L += ["## Per deal", "", "| Deal | Bucket | Asked | Wrong | Confidence (priority, champion, risk, next step) |",
              "|---|---|---|---|---|"]
        for r in ran:
            c = r["confidence"]
            L.append(f"| {r['deal']} | {r['bucket']} | {', '.join(r['asked']) or 'none'} | "
                     f"{', '.join(r['wrong']) or 'none'} | "
                     f"{', '.join(str(c[f]) for f in capture.FIELDS)} |")
        m = capture.metrics(simulated=True)
        L += ["", "## Summary (simulated AE responses)", "",
              f"- Auto-confirm rate: {m['auto_confirm_rate']}", f"- Questions per meeting: {m['avg_questions_per_meeting']}",
              "", "| Field | Accuracy |", "|---|---|"]
        L += [f"| {f} | {v['accuracy']} |" for f, v in m["per_field_accuracy"].items()]
    L += ["", "## Not run", "", "| Deal | Reason |", "|---|---|"]
    L += [f"| {r['deal']} | {r['reason']} |" for r in rows if r["status"] != "ran"] or ["| none | |"]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["replay", "record"], default="replay")
    args = ap.parse_args()
    llm = LLMClient(mode=args.mode)
    rows = []
    for deal in cs.deals():
        try:
            rows.append(asyncio.run(run_one(deal, llm)))
        except ReplayMiss as e:
            rows.append({"deal": deal, "status": "not_run", "reason": f"no recording for step {e.step!r}"})
    OUT.write_text(report(rows, args.mode), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(r['status'] == 'ran' for r in rows)} of {len(rows)} ran")


if __name__ == "__main__":
    main()
