"""Verifier ablation: how many planted errors are caught with and without the LLM verifier,
and how many false alarms it raises on clean drafts.

Planted errors (applied to each deal's recorded recap email):
  P1 changed number         a number in the body is altered
  P2 uncommitted promise    a sentence promising something nobody committed to
  P3 superseded feature     hourly batch sync presented as current
  P4 invented person        a name that is in neither the transcript nor the CRM

"Without verifier" = deterministic checks only. "With verifier" = deterministic checks plus the
LLM verifier call. Needs replay fixtures (or live mode). Writes evals/ablation.md.
"""
from __future__ import annotations

import argparse
import asyncio
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import checks, config  # noqa: E402
from src.chain import Chain, load_context  # noqa: E402
from src.llm import LLMClient, ReplayMiss  # noqa: E402
from src.schemas import RecapEmail  # noqa: E402

DEALS = ["deal_a", "deal_b", "deal_c", "deal_x", "deal_y"]
OUT = ROOT / "evals" / "ablation.md"


def plant(recap: RecapEmail, kind: str) -> RecapEmail:
    body = recap.body
    if kind == "P1_changed_number":
        m = re.search(r"\d[\d,.]*", body)
        if m:
            digits = m.group(0)
            body = body.replace(digits, str(int(re.sub(r"\D", "", digits) or "1") + 7), 1)
        else:
            body += "\n\nYou mentioned 512 users would need access."
    elif kind == "P2_uncommitted_promise":
        body += "\n\nWe will also include a free 90 day pilot with full support."
    elif kind == "P3_superseded_feature":
        body += "\n\nAs a reminder, the warehouse connector syncs in hourly batches."
    elif kind == "P4_invented_person":
        body += "\n\nI have also looped in Gregory Thornton from our side."
    return recap.model_copy(update={"body": body})


PLANTS = ["P1_changed_number", "P2_uncommitted_promise", "P3_superseded_feature", "P4_invented_person"]


async def evaluate(mode: str) -> list[dict]:
    rows = []
    for deal in DEALS:
        llm = LLMClient(mode=mode)
        chain = Chain(llm)
        ctx = load_context(deal)
        try:
            result = await chain.run(ctx)
        except ReplayMiss as e:
            rows.append({"deal": deal, "status": "not_run", "reason": str(e)})
            continue
        clean = result.artifacts["recap_email"].original
        if clean is None:
            rows.append({"deal": deal, "status": "not_run", "reason": "no recap produced"})
            continue
        for kind in ["clean"] + PLANTS:
            recap = clean if kind == "clean" else plant(clean, kind)
            det = checks.run_artifact("recap_email", recap, ctx.transcript, ctx.crm, ctx.as_of)
            det_flag = any(not c.passed and c.severity == "high" for c in det)
            try:
                vr = await chain.verify(ctx, result, {"recap_email": recap})
                ver_flag = bool(vr.parsed) and any(not v.passed and v.severity.value == "high"
                                                   for v in vr.parsed.verdicts)
                ver_status = "ran" if vr.parsed else "error"
            except ReplayMiss as e:
                ver_flag, ver_status = False, f"not run: {e.key[:12]}"
            rows.append({"deal": deal, "status": "ran", "kind": kind, "det": det_flag,
                         "with_verifier": det_flag or ver_flag, "verifier_status": ver_status})
    return rows


def report(rows: list[dict], mode: str) -> str:
    L = ["# Verifier ablation", "", "Synthetic data, fictional company. Generated by `evals/verifier_ablation.py`.", "",
         f"- Mode: {mode}. Model: {config.MODEL}.", ""]
    not_run = [r for r in rows if r["status"] != "ran"]
    ran = [r for r in rows if r["status"] == "ran"]
    if not_run:
        L += ["## Not run", ""] + [f"- {r['deal']}: {r['reason']}" for r in not_run] + [""]
    if ran:
        L += ["## Caught planted errors", "", "| Planted error | Caught without verifier | Caught with verifier |", "|---|---|---|"]
        for kind in PLANTS:
            rs = [r for r in ran if r["kind"] == kind]
            L.append(f"| {kind} | {sum(r['det'] for r in rs)} of {len(rs)} | {sum(r['with_verifier'] for r in rs)} of {len(rs)} |")
        clean = [r for r in ran if r["kind"] == "clean"]
        L += ["", "## False alarms on clean drafts", "",
              f"- Without verifier: {sum(r['det'] for r in clean)} of {len(clean)}",
              f"- With verifier: {sum(r['with_verifier'] for r in clean)} of {len(clean)}", "",
              "## Per row", "", "| Deal | Case | Deterministic | With verifier | Verifier call |", "|---|---|---|---|---|"]
        for r in ran:
            L.append(f"| {r['deal']} | {r['kind']} | {'flag' if r['det'] else 'clean'} | "
                     f"{'flag' if r['with_verifier'] else 'clean'} | {r['verifier_status']} |")
    if not ran:
        L += ["No rows ran, so there are no ablation numbers yet.", ""]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default=None, choices=["live", "record", "replay"])
    args = ap.parse_args()
    mode = args.mode or config.MODE
    rows = asyncio.run(evaluate(mode))
    OUT.write_text(report(rows, mode), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
