"""Run the chain over all 5 transcripts and score against gold. Writes evals/results.md and results.json.

Usage:
  python evals/run_evals.py                  replay mode, 1 run, judge included
  python evals/run_evals.py --mode live --runs 3      live, reports pass@3 and flaky cases
  python evals/run_evals.py --no-judge

Nothing is hidden: every failure is listed with the deal, the check, what came out, and what was
expected. Cases that could not run (for example a missing replay fixture) are listed as not run.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from evals import judges, scoring  # noqa: E402
from src import config, record_store  # noqa: E402
from src.chain import Chain, load_context  # noqa: E402
from src.llm import LLMClient, ReplayMiss  # noqa: E402

DEALS = ["deal_a", "deal_b", "deal_c", "deal_x", "deal_y"]
GOLD = ROOT / "data" / "gold"
OUT_MD = ROOT / "evals" / "results.md"
OUT_JSON = ROOT / "evals" / "results.json"


def gold(deal: str) -> dict:
    return json.loads((GOLD / f"{deal}.json").read_text(encoding="utf-8"))


async def run_one(deal: str, mode: str, with_judge: bool) -> dict:
    llm = LLMClient(mode=mode)
    try:
        result = await Chain(llm).run(load_context(deal))
    except ReplayMiss as e:
        return {"deal": deal, "status": "not_run", "reason": str(e), "step": e.step, "key": e.key}
    r = result.to_dict()
    g = gold(deal)
    if mode in {"live", "record"}:
        record_store.save_debrief(result.debrief_id, deal, result.prompt_versions, r)
    scored = {
        "deal": deal, "status": "ran", "debrief_id": result.debrief_id, "errors": r["errors"],
        "state": scoring.score_state(g, r),
        "extraction": scoring.extraction_scores(g, r.get("extraction") or {}),
        "traps": [scoring.score_trap(t, r) for t in g["traps"]],
        "adversarial": scoring.score_adversarial(g, r),
        "grounding": scoring.score_grounding(r),
        "overclaim": scoring.score_overclaim(r),
        "steps": scoring.score_steps(r),
        "needs_review": [k for k, v in r["artifacts"].items() if v["needs_review"]],
        "overrides": r["overrides"], "cost_usd": r["cost_usd"], "latency_ms": r["latency_ms"],
        "cache_read_tokens": sum(c["cache_read_input_tokens"] for c in r["calls"]),
        "cache_write_tokens": sum(c["cache_creation_input_tokens"] for c in r["calls"]),
        "n_calls": sum(c["attempts"] for c in r["calls"]),
        "steps_output": (r["artifacts"].get("assessment") or {}).get("current", {}) or {},
    }
    scored["judge"] = []
    if with_judge:
        for i, step in enumerate(scored["steps_output"].get("next_steps", []), 1):
            try:
                jr = await judges.judge_step(llm, deal, step, result.debrief_id)
            except ReplayMiss as e:
                scored["judge"].append({"step": i, "status": "not_run", "reason": str(e)})
                continue
            if jr.parsed is None:
                scored["judge"].append({"step": i, "status": "error", "reason": jr.parse_error or "refused"})
            else:
                scored["judge"].append({"step": i, "status": "ran", "passed": judges.overall(jr.parsed),
                                        **jr.parsed.model_dump(mode="json")})
    return scored


def case_results(s: dict) -> dict[str, bool]:
    """Flatten one scored run into named pass or fail cases for pass@k."""
    if s["status"] != "ran":
        return {}
    out = {"deal_state": s["state"]["passed"], "steps": s["steps"]["passed"], "overclaim": s["overclaim"]["passed"]}
    for t in s["traps"]:
        out[t["id"]] = t["passed"]
    if s["adversarial"]:
        out[s["adversarial"]["id"]] = s["adversarial"]["passed"]
    for k, v in s["grounding"].items():
        out[f"grounding:{k}"] = v["passed"]
    return out


def write_report(runs: dict[str, list[dict]], mode: str, n_runs: int, with_judge: bool) -> str:
    L = ["# Eval results", "",
         "Synthetic data, fictional company. Generated by `evals/run_evals.py`; do not edit by hand except the "
         "\"What changed\" column of the failures table.", "",
         f"- Mode: {mode}. Runs per deal: {n_runs}. Model: {config.MODEL}.",
         f"- Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
         f"- Judge: {'calibrated' if judges.status()['calibrated'] else 'uncalibrated'} "
         f"(see `python evals/judges.py status`).", ""]

    not_run = [s for ss in runs.values() for s in ss if s["status"] != "ran"]
    ran = [s for ss in runs.values() for s in ss if s["status"] == "ran"]
    if not ran:
        L += ["## Status: nothing ran", "",
              "No scores exist yet. Every case below is listed as not run, with the reason. No numbers are invented.", ""]

    if not_run:
        L += ["## Not run", "", "| Deal | Reason |", "|---|---|"]
        for s in not_run:
            L.append(f"| {s['deal']} | {s['reason']} |")
        L.append("")

    if ran:
        first = {d: next((s for s in ss if s["status"] == "ran"), None) for d, ss in runs.items()}
        L += ["## Summary (first run per deal)", "",
              "| Deal | State (got / expected) | Traps | Adversarial | Grounding | Steps | Overclaim | Needs review | Calls | Cost | Latency | Cache read tokens |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for d, s in first.items():
            if not s:
                continue
            traps = ", ".join(f"{t['id']} {'pass' if t['passed'] else 'FAIL'}" for t in s["traps"]) or "none"
            adv = (f"{s['adversarial']['id']} {'pass' if s['adversarial']['passed'] else 'FAIL'}"
                   if s["adversarial"] else "n/a")
            grounding = "pass" if all(v["passed"] for v in s["grounding"].values()) else "FAIL"
            L.append(f"| {d} | {s['state']['got']} / {s['state']['expected']} {'pass' if s['state']['passed'] else 'FAIL'} "
                     f"| {traps} | {adv} | {grounding} | {'pass' if s['steps']['passed'] else 'FAIL'} "
                     f"| {'pass' if s['overclaim']['passed'] else 'FAIL'} | {', '.join(s['needs_review']) or 'none'} "
                     f"| {s['n_calls']} | ${s['cost_usd']:.4f} | {s['latency_ms'] / 1000:.1f}s | {s['cache_read_tokens']} |")
        L.append("")

        L += ["## Extraction recall and precision (first run, counts)", "",
              "| Deal | Objections R | Objections P | Commitments R | Commitments P | Stakeholders R | Stakeholders P | Open items R | Open items P |",
              "|---|---|---|---|---|---|---|---|---|"]
        totals = {k: [0, 0, 0, 0] for k in scoring.SCORED_LISTS}
        for d, s in first.items():
            if not s:
                continue
            row = [d]
            for k in scoring.SCORED_LISTS:
                e = s["extraction"][k]
                row += [scoring.fmt_count(e["recall"]), scoring.fmt_count(e["precision"])]
                totals[k][0] += e["recall"][0]; totals[k][1] += e["recall"][1]
                totals[k][2] += e["precision"][0]; totals[k][3] += e["precision"][1]
            L.append("| " + " | ".join(row) + " |")
        L.append("| all | " + " | ".join(f"{t[0]} of {t[1]} | {t[2]} of {t[3]}" for t in totals.values()) + " |")
        L += ["", "Precision counts predicted items that overlap a gold item by utterance ID (stakeholders by name). "
                  "An unmatched prediction is not always wrong; it may be a real item the gold labels missed. Check the extras below.", ""]

        L += ["## Failures", "", "Every failing check from every run. \"What changed\" is filled in after a fix, "
              "with the decision ID from DECISIONS.md.", "",
              "| Deal | Run | Check | Output | Expected | What changed |", "|---|---|---|---|---|---|"]
        n_fail = 0
        for d, ss in runs.items():
            for i, s in enumerate(ss, 1):
                if s["status"] != "ran":
                    continue
                if not s["state"]["passed"]:
                    n_fail += 1
                    L.append(f"| {d} | {i} | deal state | {s['state']['got']} | {', '.join(s['state']['accepted'])} | |")
                for t in s["traps"] + ([s["adversarial"]] if s["adversarial"] else []):
                    if not t["passed"]:
                        n_fail += 1
                        sub = ", ".join(f"{k}={'yes' if v else 'no'}" for k, v in t["sub"].items())
                        L.append(f"| {d} | {i} | {t['id']} {t['name']} | {sub} | {t['expected']} | |")
                for k, v in s["grounding"].items():
                    if not v["passed"]:
                        n_fail += 1
                        L.append(f"| {d} | {i} | grounding: {k} | {'; '.join(v['failures'])[:300]} | all pass | |")
                if not s["steps"]["passed"]:
                    n_fail += 1
                    L.append(f"| {d} | {i} | step rules | {'; '.join(s['steps']['problems'])} | at most 3, each with evidence, owner, rule | |")
                if not s["overclaim"]["passed"]:
                    n_fail += 1
                    L.append(f"| {d} | {i} | overclaim | {'; '.join(s['overclaim']['first_draft_flags'])[:300]} | no uncommitted promises | |")
                for e in s["errors"]:
                    n_fail += 1
                    L.append(f"| {d} | {i} | chain error | {e[:300]} | no errors | |")
                for k in scoring.SCORED_LISTS:
                    for m in s["extraction"][k]["missed"]:
                        n_fail += 1
                        L.append(f"| {d} | {i} | missed {k[:-1]} | not extracted | {m} | |")
        if n_fail == 0:
            L.append("| none | | | | | |")
        L.append("")

        L += ["## Extra extracted items not in gold (first run)", "", "Review these by hand: some are noise, some are gold gaps.", ""]
        for d, s in first.items():
            if not s:
                continue
            extras = [(k, x) for k in scoring.SCORED_LISTS for x in s["extraction"][k]["extra"]]
            if extras:
                L.append(f"- {d}: " + "; ".join(f"{k}: {x}" for k, x in extras))
        L.append("")

        L += ["## Rule overrides applied (first run)", ""]
        for d, s in first.items():
            if s and s["overrides"]:
                for o in s["overrides"]:
                    L.append(f"- {d}: {o['rule_id']} on {o['target']!r}: {o['before']} to {o['after']} ({o['reason']})")
        L.append("")

        if n_runs > 1:
            L += [f"## pass@{n_runs} and flaky cases", "",
                  f"pass@{n_runs}: the case passed in at least one of {n_runs} runs. "
                  f"pass^{n_runs}: it passed in all of them. Flaky: mixed results.", "",
                  "| Deal | Case | Passed runs | pass@k | pass^k | Flaky |", "|---|---|---|---|---|---|"]
            for d, ss in runs.items():
                per = [case_results(s) for s in ss if s["status"] == "ran"]
                for case in sorted({c for p in per for c in p}):
                    vals = [p[case] for p in per if case in p]
                    L.append(f"| {d} | {case} | {sum(vals)} of {len(vals)} | {'yes' if any(vals) else 'no'} "
                             f"| {'yes' if all(vals) else 'no'} | {'yes' if 0 < sum(vals) < len(vals) else 'no'} |")
            L.append("")

        if with_judge:
            label = "calibrated" if judges.status()["calibrated"] else "uncalibrated"
            L += [f"## Judge results ({label})", "",
                  "Binary per criterion; a step passes only if all pass. Until hand labels exist and the judge is "
                  "frozen and scored on the test split, treat these as uncalibrated opinions.", "",
                  "| Deal | Step | Overall | specific | evidence_tied | playbook_tied | actionable_10_min | non_obvious | Critique |",
                  "|---|---|---|---|---|---|---|---|---|"]
            for d, s in first.items():
                for j in (s or {}).get("judge", []):
                    if j["status"] != "ran":
                        L.append(f"| {d} | {j['step']} | not run | | | | | | {j['reason'][:120]} |")
                        continue
                    yn = lambda b: "pass" if b else "fail"  # noqa: E731
                    L.append(f"| {d} | {j['step']} | {yn(j['passed'])} | {yn(j['specific'])} | {yn(j['evidence_tied'])} "
                             f"| {yn(j['playbook_tied'])} | {yn(j['actionable_10_min'])} | {yn(j['non_obvious'])} "
                             f"| {j['critique']} |")
            L.append("")

    L += ["## Related", "", "- Verifier ablation: `evals/ablation.md` (`python evals/verifier_ablation.py`).",
          "- Judge calibration: `python evals/judges.py status`.", ""]
    return "\n".join(L)


async def main_async(args) -> dict[str, list[dict]]:
    runs: dict[str, list[dict]] = {}
    for deal in args.deals:
        runs[deal] = []
        for _ in range(args.runs):
            runs[deal].append(await run_one(deal, args.mode, not args.no_judge))
            if runs[deal][-1]["status"] != "ran" and args.mode == "replay":
                break  # replay is deterministic; one miss means all runs miss
    return runs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default=None, choices=["live", "record", "replay"])
    ap.add_argument("--runs", type=int, default=None)
    ap.add_argument("--deals", nargs="*", default=DEALS)
    ap.add_argument("--no-judge", action="store_true")
    args = ap.parse_args()
    args.mode = args.mode or config.MODE
    args.runs = args.runs or (3 if args.mode == "live" else 1)
    runs = asyncio.run(main_async(args))
    OUT_JSON.write_text(json.dumps(runs, indent=1, default=str) + "\n", encoding="utf-8")
    OUT_MD.write_text(write_report(runs, args.mode, args.runs, not args.no_judge), encoding="utf-8")
    ran = sum(1 for ss in runs.values() for s in ss if s["status"] == "ran")
    print(f"wrote {OUT_MD.relative_to(ROOT)}: {ran} runs scored, "
          f"{sum(1 for ss in runs.values() for s in ss if s['status'] != 'ran')} not run")


if __name__ == "__main__":
    main()
