"""Score the tool's next steps against the research reference answers, and check judge v2 against them.

Reference answers (data/reference_steps/<deal>.json) come from docs/research/best_practice_findings.md section 5.
Each reference step is must_have, optional, routine or wrong, with keyword groups to match a tool step.

Coverage (no model calls):
- must-have coverage: share of must-have reference steps matched by at least one tool step
- wrong steps: tool steps that match a wrong reference step
- routine only: tool steps that match a routine reference step and nothing better
- state agreement: the tool's deal state against the research's

Keyword matching is a floor: it misses paraphrases, so coverage here understates a good step more often than it
overstates a bad one. After recording, an LLM matcher should replace it, checked against these same labels.

Judge check (model calls, replay or record): run judge v2 on every reference step. Must-have and optional steps
should be acceptable, wrong steps should not, and routine steps should fail R7 (beyond hygiene). Agreement is the
evidence that judge v2 can be trusted on the tool's own steps.

Run:  python evals/reference.py coverage        (replay, writes evals/reference_results.md)
      python evals/reference.py judge --mode record   (needs a key and DEBRIEF_BEST_PRACTICE=1)
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.chain import Chain, load_context  # noqa: E402
from src.llm import LLMClient, ReplayMiss  # noqa: E402

REF = ROOT / "data" / "reference_steps"
OUT = ROOT / "evals" / "reference_results.md"


def reference(deal_id: str) -> dict:
    return json.loads((REF / f"{deal_id}.json").read_text(encoding="utf-8"))


def deals() -> list[str]:
    return sorted(p.stem for p in REF.glob("deal_*.json"))


def matches(text: str, groups: list[list[str]]) -> bool:
    t = text.lower()
    return all(any(alt.lower() in t for alt in group) for group in groups)


def step_text(step: dict) -> str:
    return f"{step.get('action', '')} {step.get('why', '')}"


def score(deal_id: str, assessment: dict) -> dict:
    ref = reference(deal_id)
    steps = assessment.get("next_steps", [])
    by_kind = {k: [r for r in ref["steps"] if r["kind"] == k] for k in ("must_have", "optional", "routine", "wrong")}
    covered = [r["id"] for r in by_kind["must_have"] if any(matches(step_text(s), r["match"]) for s in steps)]
    per_step = []
    for i, s in enumerate(steps, 1):
        hits = {k: [r["id"] for r in rs if matches(step_text(s), r["match"])] for k, rs in by_kind.items()}
        label = ("wrong" if hits["wrong"] else "must_have" if hits["must_have"] else "optional" if hits["optional"]
                 else "routine" if hits["routine"] else "unmatched")
        per_step.append({"step": i, "action": s.get("action", ""), "label": label, "hits": hits})
    return {"deal": deal_id, "state_expected": ref["deal_state"], "state_got": assessment.get("deal_state", ""),
            "must_have_total": len(by_kind["must_have"]), "must_have_covered": covered,
            "wrong_steps": [p["step"] for p in per_step if p["label"] == "wrong"],
            "routine_only": [p["step"] for p in per_step if p["label"] == "routine"], "steps": per_step}


async def _assessment(deal_id: str, llm: LLMClient) -> dict:
    result = await Chain(llm).run(load_context(deal_id))
    a = result.artifacts.get("assessment")
    return a.current.model_dump(mode="json") if a and a.current else {}


def coverage_report(mode: str = "replay") -> str:
    llm = LLMClient(mode=mode)
    rows, missing = [], []
    for d in deals():
        try:
            rows.append(score(d, asyncio.run(_assessment(d, llm))))
        except ReplayMiss as e:
            missing.append((d, f"no recording for step {e.step!r}"))
    total = sum(r["must_have_total"] for r in rows)
    covered = sum(len(r["must_have_covered"]) for r in rows)
    L = ["# Next steps against best practice", "",
         "Synthetic data, fictional company. Generated by `evals/reference.py coverage`. Reference answers come from "
         "`docs/research/best_practice_findings.md` section 5. Matching is by keywords, a floor that misses paraphrases.",
         "", f"- Mode: {mode}. Deals scored: {len(rows)} of {len(deals())}.",
         f"- Must-have steps covered: {covered} of {total}.",
         f"- Tool steps matching a wrong step: {sum(len(r['wrong_steps']) for r in rows)}.",
         f"- Tool steps that are routine only: {sum(len(r['routine_only']) for r in rows)}.",
         f"- Deal state agrees with the research: {sum(r['state_got'] == r['state_expected'] for r in rows)} of {len(rows)}.",
         "", "| Deal | State (got / research) | Must-have covered | Tool steps (label) |", "|---|---|---|---|"]
    for r in rows:
        labels = "; ".join(f"{p['step']}: {p['label']}" for p in r["steps"]) or "none"
        L.append(f"| {r['deal']} | {r['state_got']} / {r['state_expected']} | "
                 f"{len(r['must_have_covered'])} of {r['must_have_total']} ({', '.join(r['must_have_covered']) or 'none'}) "
                 f"| {labels} |")
    L += ["", "## Tool steps", ""]
    for r in rows:
        for p in r["steps"]:
            L.append(f"- {r['deal']} step {p['step']} ({p['label']}): {p['action']}")
    if missing:
        L += ["", "## Not run", ""] + [f"- {d}: {why}" for d, why in missing]
    return "\n".join(L) + "\n"


async def judge_check(mode: str) -> dict:
    from evals import judges
    if judges.judge_version() == "v1":
        raise SystemExit("judge v2 is off. Set DEBRIEF_BEST_PRACTICE=1.")
    llm = LLMClient(mode=mode)
    rows = []
    for d in deals():
        for r in reference(d)["steps"]:
            step = {"action": r["text"], "owner": r["owner"], "due_by": r["due_by"],
                    "playbook_rule_id": (r["rules"] or [""])[0], "release_card_id": "", "action_type": "other",
                    "why": "", "evidence": []}
            res = await judges.judge_step(llm, d, step, f"refjudge-{r['id']}")
            if res.parsed is None:
                rows.append({"id": r["id"], "kind": r["kind"], "error": res.parse_error or "refused"})
                continue
            j = res.parsed
            expected = {"must_have": True, "optional": True, "wrong": False}.get(r["kind"])
            got = judges.overall(j)
            agree = (got == expected) if expected is not None else (not j.r7_beyond_hygiene)
            rows.append({"id": r["id"], "kind": r["kind"], "acceptable": got, "r7": j.r7_beyond_hygiene,
                         "agree": agree, "critique": j.critique})
    ok = [x for x in rows if "agree" in x]
    by = {k: f"{sum(x['agree'] for x in ok if x['kind'] == k)} of {sum(1 for x in ok if x['kind'] == k)}"
          for k in ("must_have", "optional", "routine", "wrong")}
    return {"agreement": by, "rows": rows}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["coverage", "judge"])
    ap.add_argument("--mode", default="replay", choices=["replay", "record", "live"])
    args = ap.parse_args()
    if args.command == "coverage":
        OUT.write_text(coverage_report(args.mode), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        out = asyncio.run(judge_check(args.mode))
        (ROOT / "evals" / "judge_reference_check.json").write_text(json.dumps(out, indent=2) + "\n")
        print(json.dumps(out["agreement"], indent=2))


if __name__ == "__main__":
    main()
